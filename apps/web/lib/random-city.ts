/**
 * Pick a random anime name that has not been used yet by this user.
 */
export function getRandomAnimeName(usedNames: Set<string>): string {
  const available = ANIME.filter((name) => !usedNames.has(name));

  if (available.length > 0) {
    return available[Math.floor(Math.random() * available.length)]!;
  }

  const base = ANIME[Math.floor(Math.random() * ANIME.length)]!;
  let suffix = 2;
  while (usedNames.has(`${base}-${suffix}`)) {
    suffix++;
  }
  return `${base}-${suffix}`;
}

// Compatibility for existing imports; session creation now gets anime names.
export const getRandomCityName = getRandomAnimeName;
